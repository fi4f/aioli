import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const files = [];
async function collect(directory, target, accept) {
  const entries = await fs.readdir(path.join(root, directory), { withFileTypes: true });
  entries.sort((a, b) => a.name.localeCompare(b.name));
  for (const entry of entries) {
    const source = `${directory}/${entry.name}`;
    const destination = `${target}/${entry.name}`;
    if (entry.isDirectory()) await collect(source, destination, accept);
    else if (accept(entry.name)) {
      const extension = path.extname(entry.name).toLowerCase();
      const mime =
        {
          '.png': 'image/png',
          '.jpg': 'image/jpeg',
          '.svg': 'image/svg+xml',
          '.js': 'text/javascript',
        }[extension] ?? 'text/plain;charset=utf-8';
      files.push({
        path: destination,
        source: `../${source}`,
        text: ['.lisp', '.js', '.md', '.json', '.txt', '.svg'].includes(extension),
        mime,
      });
    }
  }
}
await collect('editor', '/editor', (name) => /\.(lisp|png|jpg|svg)$/u.test(name));
await collect('examples', '/project', (name) => /\.(lisp|js)$/u.test(name));
files.push({
  path: '/editor/ui.lisp',
  source: '../hg/ui.lisp',
  text: true,
  mime: 'text/plain;charset=utf-8',
});
await fs.writeFile(
  path.join(root, 'hg/vfs-seed.generated.js'),
  `// Generated by hg/tools/generate-vfs-seed.mjs. Default self-contained editor/project files.\nexport const VfsSeed = ${JSON.stringify(files, null, 2)};\n`,
);
